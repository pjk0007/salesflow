-- 사업부 넘버링(회사 원칙): 매치스플랜·워크투하이어 0, 디하 계열 1, 백오피스랩 2, 픽셀앤로직 3, 오피오 4, 마케터하이어 5, 스마트팩토리(KSFC) 7, 설비지원몰 8, 일본 9 (2026-11-12 주희님)
-- 화면에서 "1-디하"처럼 붙여 보여준다. 번호+이름이 같을 때만. 나머지는 설정에서 넣는다.
UPDATE "workspaces" w
SET "settings" = coalesce(w."settings", '{}'::jsonb) || jsonb_build_object('displayNo', v.no)
FROM (VALUES
    (15, '매치스플랜', '0'),
    (23, '워크투하이어', '0'),
    (8, '디하', '1'),
    (11, '디하파트너즈', '1'),
    (9, '백오피스랩', '2'),
    (10, '픽셀앤로직', '3'),
    (14, '오피오', '4'),
    (17, '마케터하이어', '5'),
    (22, 'KSFC', '7'),
    (21, '설비지원몰', '8'),
    (18, '일본', '9')
) AS v(id, name, no)
WHERE w."id" = v.id AND w."name" = v.name;
